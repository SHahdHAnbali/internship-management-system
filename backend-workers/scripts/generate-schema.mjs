// Regenerates test/schema.sql from the EF Core migrations in ../backend (the owner of the database schema), so the
// Worker tests run against exactly the schema production has: tables, constraints, indexes, the no-delete and audit
// triggers, seed rows and __EFMigrationsHistory. Requires the .NET SDK (`dotnet tool restore` at the repo root).
// Usage: npm run schema:generate
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const backend = new URL('../../backend/', import.meta.url).pathname;
const target = new URL('../test/schema.sql', import.meta.url).pathname;
const work = mkdtempSync(join(tmpdir(), 'ims-schema-'));
try {
  const output = join(work, 'schema.sql');
  execFileSync(
    'dotnet',
    ['ef', 'migrations', 'script', '-p', 'src/Ims.Infrastructure', '-s', 'src/Ims.Api', '-o', output],
    { cwd: backend, stdio: 'inherit' },
  );
  const sql = readFileSync(output, 'utf8').replace(/^﻿/, '');
  writeFileSync(
    target,
    '-- GENERATED by `npm run schema:generate` from the EF Core migrations in ../backend. Do not edit.\n' +
      '-- Used only to create disposable test databases; production schema changes go through EF Core migrations.\n' +
      sql,
  );
  console.log(`Wrote ${target}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
